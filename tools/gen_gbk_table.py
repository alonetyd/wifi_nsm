#!/usr/bin/env python3
"""
GB2312 (GBK 二级汉字前) → Unicode 转换表生成器.

覆盖 GB2312 全部字符:
  - 0xA1-0xA9 区: 常用符号 (全角 ASCII / 数字 / 标点 / 9 个区)
  - 0xB0-0xD7 区: 一级汉字 (16 区, 按拼音排序)
  - 0xD8-0xF7 区: 二级汉字 (72 区, 按部首排序)

输出 C 源数据 (直接嵌入 gbk_to_unicode.c).
"""

import os

def build_gb2312_table():
    rows = list(range(0xA1, 0xF8))  # 0xA1..0xF7 共 87 行
    cells = list(range(0xA1, 0xFE + 1))  # 0xA1..0xFE 共 94 列
    result = {}
    for hi in rows:
        row = []
        for lo in cells:
            try:
                b = bytes([hi, lo])
                s = b.decode('gb2312')
                cp = ord(s[0])
                row.append(cp)
            except UnicodeDecodeError:
                row.append(0)
        result[hi] = row
    return result

def gen_c_array():
    table = build_gb2312_table()
    rows = sorted(table.keys())

    offsets = []
    sizes = []
    data = []
    pos = 0
    for hi in rows:
        row = table[hi]
        last_nz = -1
        for i, v in enumerate(row):
            if v != 0:
                last_nz = i
        size = last_nz + 1 if last_nz >= 0 else 0
        offsets.append(pos)
        sizes.append(size)
        data.extend(row[:size])
        pos += size

    out_lines = []
    out_lines.append("/* Auto-generated by tools/gen_gbk_table.py - DO NOT EDIT. */")
    out_lines.append("static const uint16_t unicode_table[] = {")
    chunk = []
    for i, v in enumerate(data):
        chunk.append("0x{:04X}".format(v))
        if (i + 1) % 12 == 0:
            out_lines.append("    " + ", ".join(chunk) + ",")
            chunk = []
    if chunk:
        out_lines.append("    " + ", ".join(chunk))
    out_lines.append("};")
    out_lines.append("#define UNICODE_TABLE_SIZE {}".format(len(data)))
    out_lines.append("")

    out_lines.append("static const int gbk_offset[87] = {")
    for i in range(0, 87, 10):
        chunk = []
        for j in range(i, min(i + 10, 87)):
            v = offsets[j]
            chunk.append("{:4d}".format(v))
        out_lines.append("    " + ", ".join(chunk) + ",")
    out_lines.append("};")
    out_lines.append("")

    out_lines.append("static const uint8_t gbk_size[87] = {")
    for i in range(0, 87, 15):
        chunk = []
        for j in range(i, min(i + 15, 87)):
            v = sizes[j]
            chunk.append("{:3d}".format(v))
        out_lines.append("    " + ", ".join(chunk) + ",")
    out_lines.append("};")
    out_lines.append("")

    return "\n".join(out_lines)

if __name__ == "__main__":
    out_path = os.path.join(os.path.dirname(__file__), "gbk_table_data.txt")
    with open(out_path, "w", encoding="ascii") as f:
        f.write(gen_c_array())
    print("wrote:", out_path)